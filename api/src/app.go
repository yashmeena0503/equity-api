const ADMIN_UNID = "00000000000000000000000000"

func getEnv(key, fallback string) string {
	if val, ok := os.LookupEnv(key); ok { return val }
	return fallback
}
type Config struct {
	// Environment variables.
	PORT            string
	DB_HOST         string
	DB_PORT         string
	DB_USER         string
	DB_PASS         string
	DB_NAME         string
	PAYOUT_INTERVAL string
}
// Builds a database connection string from the Config.
func (c *Config) DSN() string {
	return fmt.Sprintf(
		"%s:%s@tcp(%s:%s)/%s?parseTime=true&timeout=10s",
		c.DB_USER, c.DB_PASS, c.DB_HOST, c.DB_PORT, c.DB_NAME,
	)
}
// Loads Environment variables to struct.
func LoadConfig() *Config {
	return &Config {
		PORT:            getEnv("PORT",            "1234"),
		DB_HOST:         getEnv("DB_HOST",         "localhost"),
		DB_PORT:         getEnv("DB_PORT",         "1234"),
		DB_USER:         getEnv("DB_USER",         "user"),
		DB_PASS:         getEnv("DB_PASS",         "password"),
		DB_NAME:         getEnv("DB_NAME",         "equity"),
		PAYOUT_INTERVAL: getEnv("PAYOUT_INTERVAL", "60"), // in seconds
	}
}

type App struct {
	DB *sql.DB
	Queries *db.Queries // generated by sqlc
	Payout *PayoutBuffer
}
// Connects to the Database and returns a ready-to-use App.
func NewApp(c *Config) (*App, error) {

	// Connect to Database.
	database, err := sql.Open("mysql", c.DSN())
	if err != nil {
		slog.Error("Failed to open database connection", "err", err)
		return nil, ErrOpenDB(err)
	}
	if err := database.Ping(); err != nil {
		slog.Error("Failed to ping database", "err", err)
		return nil, ErrPingDB(err)
	}

	return &App {
		DB: database,
		Queries: db.New(database),
		Payout: &PayoutBuffer { queue: make(PayoutQueue) },
	}, nil

}
// Cleans up resources, Call it with defer in Main.
func (a *App) Close() error {
	return a.DB.Close()
}
// Create-if-not-exist all the Tables from Schema.
func (a *App) InitPresetSchema() {
	data, err := os.ReadFile("sql/schema.sql")
	if err != nil { slog.Error("Failed to read file schema.sql"); panic(err) }
	for stmt := range strings.SplitSeq(string(data), ";") {
		stmt = strings.TrimSpace(stmt)
		if stmt == "" { continue }
		if _, err := a.DB.Exec(stmt); err != nil { slog.Error("Failed to initialize schemas"); panic(err) }
	}
	slog.Info("Initialized Preset Schemas")
}
func (a *App) InitPresetRows() {
	rows := []string {
	}

	// admin user entry
	rows = append(rows, fmt.Sprintf("INSERT IGNORE INTO users (unid) VALUES ('%s')", ADMIN_UNID))

	// platforms
	for _, platform := range PlatformTypes {
		rows = append(rows, fmt.Sprintf("INSERT IGNORE INTO platform_types (name) VALUES ('%s')", platform))
	}

	// transaction_reasons
	for _, transaction_reason := range TransactionReasons {
		rows = append(rows, fmt.Sprintf("INSERT IGNORE INTO transaction_reasons (name) VALUES ('%s')", transaction_reason))
	}

	for _, stmt := range rows {
		if _, err := a.DB.Exec(stmt); err != nil {
			slog.Error("Failed to initialize preset row", "stmt", stmt, "err", err)
			panic(err)
		}
	}
	slog.Info("Initialized Preset Rows")
}
